#!/usr/bin/env python3
"""Import exact World Bank country and indicator data into MySQL.

The World Bank v2 API is public and does not require an API key.
This importer deliberately fetches live observations instead of embedding
rounded development values in the repository.
"""
from __future__ import annotations

import argparse
import json
import urllib.parse
import urllib.request
from dataclasses import dataclass
from datetime import datetime, timezone

API = "https://api.worldbank.org/v2"

INDICATORS = {
    "SP.POP.TOTL": "Population, total",
    "NY.GDP.MKTP.CD": "GDP (current US$)",
    "NY.GDP.PCAP.CD": "GDP per capita (current US$)",
    "SP.DYN.LE00.IN": "Life expectancy at birth, total (years)",
    "SL.UEM.TOTL.ZS": "Unemployment, total (% of total labor force)",
}

@dataclass
class Observation:
    iso3: str
    indicator_code: str
    indicator_name: str
    year: int
    value: float | int


def get_json(path: str, **params):
    query = urllib.parse.urlencode(params)
    url = f"{API}/{path}?{query}"
    req = urllib.request.Request(url, headers={"User-Agent": "Asm-Fortran-Dos-2.5-world-data-import/1.0"})
    with urllib.request.urlopen(req, timeout=60) as response:
        return json.load(response)


def fetch_countries():
    payload = get_json("country", format="json", per_page=400)
    rows = payload[1]
    return [r for r in rows if r.get("region", {}).get("value") != "Aggregates"]


def fetch_indicator(code: str, start: int, end: int):
    payload = get_json(
        f"country/all/indicator/{urllib.parse.quote(code, safe='.')}",
        format="json", date=f"{start}:{end}", per_page=400,
    )
    rows = payload[1] if len(payload) > 1 else []
    return [
        Observation(
            iso3=r["countryiso3code"], indicator_code=code,
            indicator_name=INDICATORS.get(code, r.get("indicator", {}).get("value", code)),
            year=int(r["date"]), value=r["value"],
        )
        for r in rows if r.get("countryiso3code") and r.get("value") is not None
    ]


def sql_quote(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def write_sql(output, countries, observations):
    generated = datetime.now(timezone.utc).isoformat()
    with open(output, "w", encoding="utf-8") as f:
        f.write("-- Generated by TOOLS/worldbank_import.py\n")
        f.write(f"-- Generated at UTC: {generated}\n")
        f.write("-- Source: World Bank Indicators API v2, source 2 (World Development Indicators).\n\n")
        f.write("CREATE TABLE IF NOT EXISTS world_countries (\n")
        f.write("  iso2 CHAR(2) PRIMARY KEY, iso3 CHAR(3) NOT NULL UNIQUE,\n")
        f.write("  country_name VARCHAR(150) NOT NULL, region_name VARCHAR(150),\n")
        f.write("  income_level VARCHAR(100), lending_type VARCHAR(100),\n")
        f.write("  capital_city VARCHAR(150), latitude DECIMAL(10,7), longitude DECIMAL(10,7),\n")
        f.write("  source_name VARCHAR(100) NOT NULL DEFAULT 'World Bank'\n"); f.write(");\n\n")
        f.write("INSERT INTO world_countries (iso2,iso3,country_name,region_name,income_level,lending_type,capital_city,latitude,longitude) VALUES\n")
        rows = []
        for c in countries:
            rows.append("(" + ",".join([
                sql_quote(c.get("iso2code")), sql_quote(c.get("id")), sql_quote(c.get("name")),
                sql_quote(c.get("region", {}).get("value")), sql_quote(c.get("incomeLevel", {}).get("value")),
                sql_quote(c.get("lendingType", {}).get("value")), sql_quote(c.get("capitalCity")),
                sql_quote(float(c["latitude"]) if c.get("latitude") else None),
                sql_quote(float(c["longitude"]) if c.get("longitude") else None),
            ]) + ")")
        f.write(",\n".join(rows) + "\nON DUPLICATE KEY UPDATE country_name=VALUES(country_name), region_name=VALUES(region_name), income_level=VALUES(income_level), lending_type=VALUES(lending_type), capital_city=VALUES(capital_city), latitude=VALUES(latitude), longitude=VALUES(longitude);\n\n")
        f.write("CREATE TABLE IF NOT EXISTS world_indicators (\n  iso3 CHAR(3) NOT NULL, indicator_code VARCHAR(32) NOT NULL, indicator_name VARCHAR(255) NOT NULL, year SMALLINT NOT NULL, value_decimal DECIMAL(30,10), source_name VARCHAR(100) NOT NULL DEFAULT 'World Bank WDI', PRIMARY KEY (iso3,indicator_code,year)\n);\n\n")
        f.write("INSERT INTO world_indicators (iso3,indicator_code,indicator_name,year,value_decimal) VALUES\n")
        rows = ["(%s,%s,%s,%s,%s)" % (sql_quote(o.iso3),sql_quote(o.indicator_code),sql_quote(o.indicator_name),o.year,sql_quote(o.value)) for o in observations]
        f.write(",\n".join(rows) + "\nON DUPLICATE KEY UPDATE indicator_name=VALUES(indicator_name), value_decimal=VALUES(value_decimal);\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--start", type=int, default=2020)
    parser.add_argument("--end", type=int, default=2024)
    parser.add_argument("--output", default="MYSQL/worldbank_live_snapshot.sql")
    args = parser.parse_args()

    countries = fetch_countries()
    observations = []
    for code in INDICATORS:
        observations.extend(fetch_indicator(code, args.start, args.end))
    write_sql(args.output, countries, observations)
    print(f"Wrote {len(countries)} country records and {len(observations)} indicator observations to {args.output}")

if __name__ == "__main__":
    main()
